import time
import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import eigh
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.neural_network import MLPClassifier, MLPRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, mean_absolute_error

rng = np.random.default_rng(42)

# Beam settings (aluminium cantilever)
L, b, h = 1.0, 0.03, 0.005
E, rho = 70e9, 2700.0
A, I = b * h, b * h**3 / 12
N_EL, N_MODES, NOISE = 20, 5, 0.002

def beam_frequencies(damage_el=None, severity=0.0):
    le = L / N_EL
    n = 2 * (N_EL + 1)
    K, M = np.zeros((n, n)), np.zeros((n, n))
    mc = rho * A * le / 420.0
    for e in range(N_EL):
        ei = E * I * ((1 - severity) if e == damage_el else 1)
        k = ei / le**3 * np.array([[12, 6*le, -12, 6*le],
                                   [6*le, 4*le**2, -6*le, 2*le**2],
                                   [-12, -6*le, 12, -6*le],
                                   [6*le, 2*le**2, -6*le, 4*le**2]])
        m = mc * np.array([[156, 22*le, 54, -13*le],
                           [22*le, 4*le**2, 13*le, -3*le**2],
                           [54, 13*le, 156, -22*le],
                           [-13*le, -3*le**2, -22*le, 4*le**2]])
        s = slice(2*e, 2*e + 4)
        K[s, s] += k
        M[s, s] += m
    K, M = K[2:, 2:], M[2:, 2:]
    w2 = eigh(K, M, eigvals_only=True, subset_by_index=[0, N_MODES - 1])
    return np.sqrt(w2) / (2 * np.pi)

def make_dataset(n_samples):
    X, loc, sev = [], [], []
    t0 = time.perf_counter()
    fh = beam_frequencies()
    for _ in range(n_samples):
        if rng.random() < 0.15:
            f, l, s = fh.copy(), 0, 0.0
        else:
            el = int(rng.integers(0, N_EL))
            s = rng.uniform(0.05, 0.5)
            f, l = beam_frequencies(el, s), el + 1
        f = f * (1 + rng.normal(0, NOISE, f.shape))
        X.append(f / fh); loc.append(l); sev.append(s * 100)
    return np.array(X), np.array(loc), np.array(sev), (time.perf_counter() - t0) / n_samples

print("Making data...")
X, loc, sev, t_fem = make_dataset(3000)
print(f"FEM time per case: {t_fem*1000:.2f} ms")

Xtr, Xte, ltr, lte, str_, ste = train_test_split(X, loc, sev, test_size=0.25, random_state=0)
sc = StandardScaler().fit(Xtr)
Xtr_s, Xte_s = sc.transform(Xtr), sc.transform(Xte)

models = {
    "Random Forest": (RandomForestClassifier(n_estimators=300, random_state=0),
                      RandomForestRegressor(n_estimators=300, random_state=0)),
    "Neural Network": (MLPClassifier(hidden_layer_sizes=(128, 64), max_iter=800, random_state=0),
                       MLPRegressor(hidden_layer_sizes=(128, 64), max_iter=800, random_state=0)),
}

print("\nRESULTS (unseen noisy test data)")
print(f"{'Model':<16}{'Location acc':>13}{'Within 1 el':>13}{'Severity err %':>16}{'Predict ms':>12}")
best_pred = None
for name, (clf, reg) in models.items():
    clf.fit(Xtr_s, ltr); reg.fit(Xtr_s, str_)
    t0 = time.perf_counter()
    lp, sp = clf.predict(Xte_s), reg.predict(Xte_s)
    tp = (time.perf_counter() - t0) / len(Xte_s) * 1000
    print(f"{name:<16}{accuracy_score(lte, lp):>13.1%}{np.mean(np.abs(lte-lp)<=1):>13.1%}"
          f"{mean_absolute_error(ste, sp):>16.2f}{tp:>12.3f}")
    if name == "Neural Network":
        best_pred = lp

plt.figure(figsize=(5, 5))
plt.scatter(lte, best_pred, alpha=0.3)
plt.plot([0, 20], [0, 20], "r--", label="perfect")
plt.xlabel("True damage location (element)")
plt.ylabel("AI predicted location")
plt.title("Damage location: true vs predicted")
plt.legend()
plt.savefig("result_plot.png", dpi=150)
plt.show()
print("\nGraph saved as result_plot.png (see the folder icon on the left)")